def test_presets(image_num: int, env_num: int) -> List[DatasetPreset]:
    scenarios = [
        ("wall_blind_corner_test", "wall_blind_corner", 7, 9000),
        ("room_doorway_test", "doorway", 6, 9020),
        ("maze_t_junction_test", "t_junction", 3, 9040),
        ("occluded_forest_test", "occluded_forest", 5, 9060),
        ("limited_fov_wall_test", "limited_fov", 7, 9080),
        ("random_columns_test", "random_columns", 2, 9100),
    ]
    return [
        DatasetPreset(
            name=name,
            split="oarm_fixed_test",
            scenario=scenario,
            weight=1.0 / len(scenarios),
            seed=seed,
            maze_type=maze_type,
            env_num=env_num,
            image_num=image_num,
            save_subdir=f"oarm_v1_test/{name}",
            safe_dist=0.7,
            max_depth_dist=12.0 if "limited_fov" in name else 16.0,
            notes="Fixed-seed test preset; do not train on this split.",
        )
        for name, scenario, maze_type, seed in scenarios
    ]


