import argparse
import json
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Dict, Iterable, List


@dataclass(frozen=True)
class DatasetPreset:
    name: str
    split: str
    scenario: str
    weight: float
    seed: int
    maze_type: int
    env_num: int
    image_num: int
    save_subdir: str
