def write_runbook(output_dir: Path, presets: Iterable[DatasetPreset]) -> None:
    lines = [
        "# OARM Dataset V1 Presets",
        "",
        "These files are generated configs for the existing YOPO Simulator.",
        "They do not modify Simulator source code by themselves.",
        "",
        "The current `dataset_generator` binary reads `Simulator/src/config/config.yaml`",
        "because that path is compiled in CMake. For each preset, copy the YAML to",
        "that path only during generation, run the generator, then restore the original",
        "config.",
        "",
        "Example:",
        "",
        "```bash",
        "cp Simulator/src/config/config.yaml /tmp/oarm_sim_config_backup.yaml",
        "cp OARM/configs/dataset_generation/oarm_v1/wall_blind_corner_train.yaml Simulator/src/config/config.yaml",
        "cd Simulator",
        "source devel/setup.bash",
        "rosrun sensor_simulator dataset_generator",
        "cp /tmp/oarm_sim_config_backup.yaml src/config/config.yaml",
        "```",
        "",
        "Generated presets:",
        "",
    ]
    for preset in presets:
        lines.append(
            f"- `{preset.name}.yaml`: split={preset.split}, scenario={preset.scenario}, "
            f"maze_type={preset.maze_type}, seed={preset.seed}, "
            f"maps={preset.env_num}, images/map={preset.image_num}"
        )
    (output_dir / "RUNBOOK.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def build_presets(args: argparse.Namespace) -> List[DatasetPreset]:
    presets = train_presets(args.train_image_num, args.train_env_num)
    if args.include_test:
        presets.extend(test_presets(args.test_image_num, args.test_env_num))
    return presets


def write_outputs(output_dir: Path, presets: List[DatasetPreset]) -> Dict:
    output_dir.mkdir(parents=True, exist_ok=True)
    manifest = {
        "name": "oarm_dataset_v1",
        "format": "YOPO-compatible",
        "presets": [asdict(preset) for preset in presets],
        "notes": [
            "Generated files are standalone configs; Simulator source is unchanged.",
            "Do not train on presets whose split is oarm_fixed_test.",
            "Use GT reaction-margin annotation to verify hidden-risk coverage.",
        ],
    }
    for preset in presets:
        (output_dir / f"{preset.name}.yaml").write_text(render_yaml(preset), encoding="utf-8")
    (output_dir / "manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    write_runbook(output_dir, presets)
    return manifest


def parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(description="Generate OARM dataset-v1 Simulator config presets.")
    p.add_argument("--output-dir", default="OARM/configs/dataset_generation/oarm_v1")
    p.add_argument("--train-env-num", type=int, default=6)
    p.add_argument("--train-image-num", type=int, default=4000)
    p.add_argument("--include-test", action="store_true")
    p.add_argument("--test-env-num", type=int, default=2)
    p.add_argument("--test-image-num", type=int, default=500)
    p.add_argument("--print-plan", action="store_true")
    return p


def main() -> None:
    args = parser().parse_args()
    presets = build_presets(args)
    manifest = write_outputs(Path(args.output_dir), presets)
    if args.print_plan:
        print(json.dumps(manifest, indent=2))
    else:
        print(f"Wrote {len(presets)} presets to {args.output_dir}")


if __name__ == "__main__":
    main()
