    y_length: int = 60
    z_length: int = 15
    x_range: int = 40
    y_range: int = 40
    z_min: float = 0.5
    z_max: float = 4.0
    safe_dist: float = 0.5
    max_depth_dist: float = 20.0
    roll_range: float = 20.0
    pitch_range: float = 20.0
    notes: str = ""


