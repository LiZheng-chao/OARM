def write_runbook(output_dir: Path, presets: List[Preset]) -> None:
    lines = [
        "# OARM Dataset V2 Presets",
        "",
        "V2 fixes two V1 issues: preset weights now control actual image counts,",
        "and limited depth range is separated from limited FOV.",
        "",
        "After generating individual sub-datasets, merge train roots with:",
        "",
        "```bash",
        "python3 -m OARM.tools.merge_yopo_datasets \\",
        "  --input-root dataset/oarm_v2/wall_blind_corner_train \\",
        "  --input-root dataset/oarm_v2/room_doorway_train \\",
        "  --input-root dataset/oarm_v2/maze_t_junction_train \\",
        "  --input-root dataset/oarm_v2/occluded_forest_train \\",
        "  --input-root dataset/oarm_v2/random_columns_train \\",
        "  --output-root dataset/oarm_v2_merged_train",
        "```",
        "",
        "Generated presets:",
        "",
    ]
    for preset in presets:
        total = preset.env_num * preset.image_num
        lines.append(
            f"- `{preset.name}.yaml`: split={preset.split}, scenario={preset.scenario}, "
            f"weight={preset.weight:.2f}, maps={preset.env_num}, images/map={preset.image_num}, total={total}"
        )
    (output_dir / "RUNBOOK.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(description="Generate corrected OARM dataset-v2 Simulator config presets.")
    p.add_argument("--output-dir", default="OARM/configs/dataset_generation/oarm_v2")
    p.add_argument("--train-env-num", type=int, default=6)
    p.add_argument("--train-total-images", type=int, default=68000)
    p.add_argument("--include-test", action="store_true")
    p.add_argument("--test-env-num", type=int, default=2)
    p.add_argument("--test-image-num", type=int, default=500)
    p.add_argument("--print-plan", action="store_true")
    return p


def main() -> None:
    args = parser().parse_args()
    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    presets = build_presets(args)
    for preset in presets:
        (output_dir / f"{preset.name}.yaml").write_text(render_yaml(preset), encoding="utf-8")
    manifest = {
        "name": "oarm_dataset_v2",
        "format": "YOPO-compatible",
        "presets": [asdict(preset) for preset in presets],
        "notes": [
            "weights control generated image counts for train presets",
            "limited_depth_range and limited_fov are separate test presets",
            "merge sub-datasets before using the current OARMDataset trainer path",
        ],
    }
    (output_dir / "manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    write_runbook(output_dir, presets)
    if args.print_plan:
        print(json.dumps(manifest, indent=2))
    else:
        print(f"Wrote {len(presets)} presets to {output_dir}")


if __name__ == "__main__":
    main()
