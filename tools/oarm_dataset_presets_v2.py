import argparse
import json
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import List, Tuple


@dataclass(frozen=True)
class Preset:
    name: str
    split: str
    scenario: str
    weight: float
    seed: int
    maze_type: int
    env_num: int
    image_num: int
    save_subdir: str
    max_depth_dist: float = 16.0
    fx: float = 80.0
    fy: float = 80.0
    safe_dist: float = 0.7
    notes: str = ""


TRAIN_SCENES: Tuple[Tuple[str, str, float, int, int, float, str], ...] = (
    ("wall_blind_corner_train", "wall_blind_corner", 0.30, 7, 2000, 14.0, "wall occlusion boundaries"),
    ("room_doorway_train", "room_doorway", 0.25, 6, 2200, 14.0, "doorway and threshold occlusion"),
    ("maze_t_junction_train", "maze_t_junction", 0.20, 3, 2400, 12.0, "corridor and branch geometry"),
    ("occluded_forest_train", "occluded_forest", 0.15, 5, 2600, 16.0, "natural occlusion behind trunks"),
    ("random_columns_train", "random_columns", 0.10, 2, 2800, 20.0, "ordinary geometric avoidance"),
)

TEST_SCENES: Tuple[Tuple[str, str, int, int, float, float, float], ...] = (
    ("wall_blind_corner_test", "wall_blind_corner", 7, 9000, 16.0, 80.0, 80.0),
    ("room_doorway_test", "doorway", 6, 9020, 16.0, 80.0, 80.0),
    ("maze_t_junction_test", "t_junction", 3, 9040, 16.0, 80.0, 80.0),
    ("occluded_forest_test", "occluded_forest", 5, 9060, 16.0, 80.0, 80.0),
    ("limited_depth_range_test", "limited_depth_range", 7, 9080, 10.0, 80.0, 80.0),
    ("limited_fov_wall_test", "limited_fov", 7, 9100, 16.0, 120.0, 120.0),
    ("random_columns_test", "random_columns", 2, 9120, 16.0, 80.0, 80.0),
)


def images_per_map(total_images: int, weight: float, env_num: int) -> int:
    return max(1, int(round(total_images * weight / max(env_num, 1))))


def build_presets(args) -> List[Preset]:
    presets: List[Preset] = []
    for name, scenario, weight, maze_type, seed, max_depth, notes in TRAIN_SCENES:
        env_num = args.train_env_num
        if scenario in {"room_doorway", "maze_t_junction", "occluded_forest"}:
            env_num = max(2, args.train_env_num // 2)
        elif scenario == "random_columns":
            env_num = max(2, args.train_env_num // 3)
        presets.append(
            Preset(
                name=name,
                split="oarm_targeted_train",
                scenario=scenario,
                weight=weight,
                seed=seed,
                maze_type=maze_type,
                env_num=env_num,
                image_num=images_per_map(args.train_total_images, weight, env_num),
                save_subdir=f"oarm_v2/{name}",
                max_depth_dist=max_depth,
                safe_dist=0.6 if scenario in {"room_doorway", "maze_t_junction", "random_columns"} else 0.7,
                notes=notes,
            )
        )
    if args.include_test:
        for name, scenario, maze_type, seed, max_depth, fx, fy in TEST_SCENES:
            presets.append(
                Preset(
                    name=name,
                    split="oarm_fixed_test",
                    scenario=scenario,
                    weight=1.0 / len(TEST_SCENES),
                    seed=seed,
                    maze_type=maze_type,
                    env_num=args.test_env_num,
                    image_num=args.test_image_num,
                    save_subdir=f"oarm_v2_test/{name}",
                    max_depth_dist=max_depth,
                    fx=fx,
                    fy=fy,
                    notes="fixed-seed test preset; do not train on this split",
                )
            )
    return presets


